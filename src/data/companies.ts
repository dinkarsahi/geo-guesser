let cachedFor: Country[] | null = null;
let cached: CompanyTarget[] = [];

/**
 * Every company whose home country is on the map, carrying that country's name
 * and its point on the map so the reveal can use both. Cached by pool identity,
 * which keeps the array stable and with it the game's memory of what it has
 * already dealt.
 */
export function companyPool(countries: Country[]): CompanyTarget[] {
  if (!countries.length) return [];
  if (countries === cachedFor) return cached;

  const byCode = new Map(countries.map((c) => [c.code, c]));
  cachedFor = countries;
  cached = ALL_COMPANIES.filter((c) => byCode.has(c.code)).map((c) => {
    const home = byCode.get(c.code)!;
    return { ...c, country: home.name, lat: home.lat, lng: home.lng };
  });
  return cached;
}
